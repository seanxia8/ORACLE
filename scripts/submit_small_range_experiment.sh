#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

ACTION="${1:-submit}"
DATA_ROOT="${DATA_ROOT:-/ceph/srv/ssjostrom/training_small_complete}"
ENERGIES="${ENERGIES:-10,20,50,100,200,500}"
FILES_PER_ENERGY_RECOIL="${FILES_PER_ENERGY_RECOIL:-5}"
NUM_STEPS="${NUM_STEPS:-5000}"
EVAL_PERIOD="${EVAL_PERIOD:-50}"
CHECKPOINT_PERIOD="${CHECKPOINT_PERIOD:-100}"
TOTAL_BATCH_SIZE="${TOTAL_BATCH_SIZE:-16}"
DEVICE_BATCH_SIZE="${DEVICE_BATCH_SIZE:-4}"
NUM_WORKERS="${NUM_WORKERS:-0}"
REQUEST_WALLTIME="${REQUEST_WALLTIME:-21600}"
REQUEST_MEMORY="${REQUEST_MEMORY:-32000}"
REQUEST_DISK="${REQUEST_DISK:-200000000}"
GPU_PROFILE="${GPU_PROFILE:-l40s}"
JOB_NAME="${JOB_NAME:-all_energies_small_complete}"
WANDB_PROJECT="${WANDB_PROJECT:-DELight_Reconstruction_Small_Range}"
RUN_STAMP="$(date +%Y%m%d_%H%M%S)"
RUN_NAME="${RUN_NAME:-${JOB_NAME}_energies_${ENERGIES//,/_}_files_${FILES_PER_ENERGY_RECOIL}_${RUN_STAMP}}"
GENERATED_JDL="scripts/submissions/submit_${JOB_NAME}.generated.jdl"
LATEST_FILE="probe_runs/${JOB_NAME}_latest_job.txt"

case "$GPU_PROFILE" in
    l40s)
        GPU_REQUIREMENTS='TARGET.GPUs_DeviceName =?= "NVIDIA L40S"'
        ACCOUNTING_GROUP="delight"
        CONTAINER_BLOCK='Universe = vanilla
+SingularityImage = "docker://cverstege/alma9-gridjob"'
        ;;
    a100)
        GPU_REQUIREMENTS='(TARGET.CloudSite == "topas") && (TARGET.GPUs_DeviceName =?= "NVIDIA A100-PCIE-40GB")'
        ACCOUNTING_GROUP="DELight"
        CONTAINER_BLOCK='Universe = docker
docker_image = cverstege/alma9-gridjob'
        ;;
    *)
        echo "ERROR: Unknown GPU_PROFILE=$GPU_PROFILE. Use l40s or a100." >&2
        exit 2
        ;;
esac

archive_logs() {
    local archive_dir="probe_runs/${JOB_NAME}_${RUN_STAMP}"
    mkdir -p "$archive_dir"
    local moved=0
    for file in "${JOB_NAME}.out" "${JOB_NAME}.err" "${JOB_NAME}.log"; do
        if [ -e "$file" ]; then
            mv "$file" "$archive_dir/$file.previous"
            moved=1
        fi
    done
    if [ "$moved" -eq 1 ]; then
        echo "Archived previous ${JOB_NAME} logs under $archive_dir"
    fi
}

join_csv() {
    local IFS=", "
    echo "$*"
}

build_transfer_list() {
    local -n out_files=$1
    local recoil energy
    out_files=(run.sh scripts reconstruction_model uv.lock pyproject.toml)

    for recoil in ER NR; do
        for energy in $(echo "$ENERGIES" | tr ',' ' '); do
            local recoil_dir="$DATA_ROOT/$recoil"
            if [ ! -d "$recoil_dir" ]; then
                echo "ERROR: Missing recoil directory: $recoil_dir" >&2
                exit 1
            fi

            mapfile -t selected < <(
                find "$recoil_dir" -maxdepth 1 -type f \
                    -name "${recoil}_traces_energy_${energy}_batch_*.h5" \
                    | sort \
                    | head -n "$FILES_PER_ENERGY_RECOIL"
            )

            if [ "${#selected[@]}" -ne "$FILES_PER_ENERGY_RECOIL" ]; then
                echo "ERROR: Found ${#selected[@]} files for $recoil energy $energy, expected $FILES_PER_ENERGY_RECOIL." >&2
                echo "Available files:" >&2
                find "$recoil_dir" -maxdepth 1 -type f -name "${recoil}_traces_energy_${energy}_batch_*.h5" -printf "  %f\n" | sort >&2
                exit 1
            fi

            out_files+=("${selected[@]}")
        done
    done
}

write_jdl() {
    local transfer_files=("$@")
    local transfer_csv
    transfer_csv="$(join_csv "${transfer_files[@]}")"
    mkdir -p "$(dirname "$GENERATED_JDL")"

    cat > "$GENERATED_JDL" <<EOF
# Auto-generated by scripts/submit_small_range_experiment.sh
# Generated at $RUN_STAMP

Executable = /bin/sh
Arguments = run.sh

Output = ${JOB_NAME}.out
Error = ${JOB_NAME}.err
Log = ${JOB_NAME}.log
stream_output = True
stream_error = True

transfer_input_files = ${transfer_csv}
transfer_output_files = artifacts, reconstruction_model/training_checkpoints
should_transfer_files = YES
when_to_transfer_output = ON_EXIT

+RequestWalltime = ${REQUEST_WALLTIME}
RequestCPUs = 1
RequestMemory = ${REQUEST_MEMORY}
request_disk = ${REQUEST_DISK}

request_GPUs = 1
+RemoteJob = True
requirements = ${GPU_REQUIREMENTS}

accounting_group = ${ACCOUNTING_GROUP}

${CONTAINER_BLOCK}

getenv = USER, USE_USER, WANDB_API_KEY
environment = "JOB_MODE=h5_transferred H5_ENERGIES=${ENERGIES} H5_FILES_PER_ENERGY_RECOIL=${FILES_PER_ENERGY_RECOIL} WANDB_MODE=online RECONSTRUCTION_DISABLE_TORCH_COMPILE=1 TORCHDYNAMO_DISABLE=1 RECONSTRUCTION_NUM_STEPS=${NUM_STEPS} RECONSTRUCTION_EVAL_STEP_PERIOD=${EVAL_PERIOD} RECONSTRUCTION_SAVE_CHECKPOINT_PERIOD=${CHECKPOINT_PERIOD} RECONSTRUCTION_TOTAL_BATCH_SIZE=${TOTAL_BATCH_SIZE} RECONSTRUCTION_DEVICE_BATCH_SIZE=${DEVICE_BATCH_SIZE} RECONSTRUCTION_NUM_WORKERS=${NUM_WORKERS} RECONSTRUCTION_WANDB_PROJECT=${WANDB_PROJECT} RECONSTRUCTION_WANDB_RUN_NAME=${RUN_NAME} RECONSTRUCTION_CHECKPOINT_DIR=artifacts/${JOB_NAME}/checkpoints/${RUN_STAMP}"

Queue
EOF
}

submit_job() {
    mkdir -p probe_runs
    archive_logs

    local transfer_files=()
    build_transfer_list transfer_files

    local h5_count total_bytes
    h5_count="$(printf "%s\n" "${transfer_files[@]}" | grep -c '\.h5$' || true)"
    total_bytes="$(printf "%s\n" "${transfer_files[@]}" | grep '\.h5$' | xargs -r stat -c '%s' | awk '{sum += $1} END {print sum + 0}')"

    echo "Preparing small-range experiment"
    echo "  Data root: $DATA_ROOT"
    echo "  Energies: $ENERGIES"
    echo "  H5 files per energy/recoil: $FILES_PER_ENERGY_RECOIL"
    echo "  H5 files transferred: $h5_count"
    echo "  H5 transfer size: $(awk -v b="$total_bytes" 'BEGIN {printf "%.2f GiB", b / 1024 / 1024 / 1024}')"
    echo "  Steps: $NUM_STEPS"
    echo "  GPU profile: $GPU_PROFILE"
    echo "  W&B project: $WANDB_PROJECT"
    echo "  W&B run: $RUN_NAME"

    if [ -z "${WANDB_API_KEY:-}" ]; then
        echo
        echo "ERROR: WANDB_API_KEY is not exported. Export it before submitting."
        echo "Example:"
        echo "  export WANDB_API_KEY='...'"
        exit 1
    fi

    write_jdl "${transfer_files[@]}"
    echo
    echo "Wrote $GENERATED_JDL"

    local submit_output cluster
    submit_output="$(condor_submit "$GENERATED_JDL")"
    echo "$submit_output"
    cluster="$(printf '%s\n' "$submit_output" | sed -n 's/.*submitted to cluster \([0-9][0-9]*\).*/\1/p' | tail -n 1)"
    if [ -n "$cluster" ]; then
        printf "%s %s %s\n" "$JOB_NAME" "$cluster" "$RUN_NAME" > "$LATEST_FILE"
        echo "Saved latest job to $LATEST_FILE"
    fi
}

show_status() {
    echo "=== Queue ==="
    condor_q "$USER" || true
    echo

    if [ -f "$LATEST_FILE" ]; then
        echo "=== Latest ${JOB_NAME} job ==="
        cat "$LATEST_FILE"
        read -r _ cluster _ < "$LATEST_FILE"
        echo
        echo "=== Condor status/history ==="
        condor_q "$cluster" -af ClusterId ProcId JobStatus HoldReason 2>/dev/null || \
            condor_history "$cluster" -limit 1 -af ClusterId ProcId JobStatus ExitCode ExitStatus CompletionDate 2>/dev/null || true
    else
        echo "No latest job file found: $LATEST_FILE"
    fi
    echo

    for file in "${JOB_NAME}.out" "${JOB_NAME}.err" "${JOB_NAME}.log"; do
        if [ -f "$file" ]; then
            echo
            echo "--- $file ---"
            tail -n 80 "$file"
        fi
    done
}

case "$ACTION" in
    submit)
        submit_job
        ;;
    status)
        show_status
        ;;
    dry-run)
        transfer_files=()
        build_transfer_list transfer_files
        write_jdl "${transfer_files[@]}"
        condor_submit -dry-run "/tmp/${JOB_NAME}.ad" "$GENERATED_JDL"
        echo "Dry run OK: $GENERATED_JDL"
        ;;
    *)
        echo "Usage: $0 [submit|status|dry-run]" >&2
        echo "Overrides: ENERGIES=10,20,50,100,200,500 FILES_PER_ENERGY_RECOIL=5 NUM_STEPS=5000 JOB_NAME=all_energies_small_complete GPU_PROFILE=l40s|a100" >&2
        exit 2
        ;;
esac
